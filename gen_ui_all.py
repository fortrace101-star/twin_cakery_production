import re
import json
from pathlib import Path
from datetime import date

root = Path('/c/Users/manue/Desktop/twin_cakery/erp')
ui_feat = root / 'skills/optim/references/ui-features.md'
progress = root / 'Optim/Optim_progress.md'
today = date.today().strftime('%Y-%m-%d')

# Parse UI features
ui_by_module = {}
current_mod = None
with open(ui_feat) as f:
    for line in f:
        m = re.match(r'^##\s+([A-Z]+):', line)
        if m:
            current_mod = m.group(1)
            ui_by_module[current_mod] = []
            continue
        if current_mod and line.strip().startswith('| UI-'):
            # parse table row
            parts = [p.strip() for p in line.split('|')]
            if len(parts) >= 6:
                ui_by_module[current_mod].append({
                    'id': parts[1],
                    'category': parts[2],
                    'feature': parts[3],
                    'type': parts[4],
                    'step': parts[5].replace('`',''),
                    'notes': parts[6] if len(parts)>6 else ''
                })

# Parse progress to get module sections and steps
with open(progress) as f:
    content = f.read()

modules = ['SEC','ORD','QUO','PROD','INV','PUR','DEL','FIN','ANA','NOT','CRM','CAT','STF','WEB','ARC']
for mod in modules:
    # find section
    pattern = rf'(## {mod}:.*?)(?=^## [A-Z]{{2,3}}:|\Z)'
    m = re.search(pattern, content, re.S | re.M)
    if not m:
        continue
    section = m.group(1)
    # get steps
    steps = re.findall(r'- \[[ x~\-]\] ([A-Z]+-\d+)', section)
    steps_set = set(steps)
    
    # build checklist
    items = ui_by_module.get(mod, [])
    checklist_lines = []
    checklist_lines.append('### UI checklist (generated by the skill when the module starts)\n')
    checklist_lines.append('<!-- UI-CHECKLIST:BEGIN -->\n')
    if not items:
        checklist_lines.append('<!-- UI-CHECKLIST:END -->\n')
    else:
        for it in items:
            step = it['step']
            # determine if list/board/table/status
            is_listy = any(k in it['type'].lower() or k in it['feature'].lower() for k in ['list','table','board','grid','kanban','status','card list','badge list'])
            # check if step is done
            step_done = False
            step_part = False
            for sm in re.finditer(r'- \[([ x~\-])\] ' + re.escape(step) + r'\b', section):
                st = sm.group(1)
                if st == 'x': step_done = True
                elif st == '~': step_part = True
            state = '[ ]'
            if step_done and False:  # don't auto-tick
                pass
            # build item
            checklist_lines.append(f"- {state} {it['id']} [ADJUST] {it['feature']} → supports {step}\n")
            checklist_lines.append(f"  - [ ] Target confirmed: {it['notes'] if it['notes'] else 'locate in code'}\n")
            checklist_lines.append(f"  - [ ] Data source: API endpoint and fields identified\n")
            checklist_lines.append(f"  - [ ] States: empty, loading, error, forbidden\n")
            checklist_lines.append(f"  - [ ] Permission gating enforced\n")
            checklist_lines.append(f"  - [ ] Responsive/theme/accessibility verified\n")
            if is_listy:
                checklist_lines.append(f"  - [ ] live update: refresh on status changes without manual reload (realtime/polling), test covers it\n")
            else:
                checklist_lines.append(f"  - [ ] live update: reviewed or not required (document reason if skipped)\n")
            checklist_lines.append(f"  - [ ] Test: unit/component test added/updated\n")
        checklist_lines.append('<!-- UI-CHECKLIST:END -->\n')
    
    new_block = ''.join(checklist_lines)
    # replace existing block
    start = section.find('### UI checklist')
    if start == -1:
        # append
        new_section = section + '\n' + new_block
    else:
        end = section.find('<!-- UI-CHECKLIST:END -->')
        if end == -1:
            new_section = section[:start] + new_block
        else:
            end_block = section.find('\n', end) if section.find('\n', end) != -1 else end + len('<!-- UI-CHECKLIST:END -->')
            new_section = section[:start] + new_block
    content = content.replace(section, new_section)

with open(progress, 'w') as f:
    f.write(content)

print('done')
